"""
DS5020 Project 7 -- Bayesian A/B Testing
Load and describe the real dataset: Cookie Cats (Kaggle).

Expected file: data/cookie_cats.csv  (see README for the download link).
Columns: userid, version (gate_30 / gate_40), sum_gamerounds, retention_1, retention_7

Writes:
  figures/retention_by_version.png
  figures/gamerounds_hist.png
  docs/data_macros.tex     (\\newcommand macros: rows, columns, missing)
  docs/data_summary.tex    (table of n and x per version, \\input by report.tex)

Only numpy, pandas and matplotlib are used.
"""
import os, sys
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "data", "cookie_cats.csv")
FIG = os.path.join(HERE, "..", "figures")
DOCS = os.path.join(HERE, "..", "docs")
os.makedirs(FIG, exist_ok=True); os.makedirs(DOCS, exist_ok=True)

if not os.path.exists(DATA):
    sys.exit("data/cookie_cats.csv not found. Download it from "
             "https://www.kaggle.com/datasets/yufengsui/mobile-games-ab-testing "
             "and save it as data/cookie_cats.csv")

df = pd.read_csv(DATA)

# ------------------------------------------------------------ description
print("shape (rows, columns):", df.shape)
print("\ncolumn types:\n", df.dtypes)
print("\nmissing values per column:\n", df.isna().sum())
print("\nduplicate userids:", df["userid"].duplicated().sum())
print("\nplayers per version:\n", df["version"].value_counts())
print("\nsum_gamerounds summary:\n", df["sum_gamerounds"].describe())

# one trial = one player; a "click" = the player returned
summary = (df.groupby("version")
             .agg(n=("userid", "size"),
                  x1=("retention_1", "sum"), x7=("retention_7", "sum"))
             .reindex(["gate_30", "gate_40"]))
summary["rate1"] = summary["x1"] / summary["n"]
summary["rate7"] = summary["x7"] / summary["n"]
print("\ncounts per version (n, x_1-day, x_7-day, rates):\n", summary)

# ------------------------------------------------------------ figures
fig, ax = plt.subplots(figsize=(5.5, 3.6))
labels = ["gate_30 (A)", "gate_40 (B)"]
xpos = np.arange(2); wdt = 0.35
for k, (col, name) in enumerate([("rate1", "1-day"), ("rate7", "7-day")]):
    p = summary[col].values; nn = summary["n"].values
    err = 1.96 * np.sqrt(p * (1 - p) / nn)          # normal-approx 95% interval
    ax.bar(xpos + (k - 0.5) * wdt, p, wdt, yerr=err, capsize=4, label=f"{name} retention")
ax.set_xticks(xpos); ax.set_xticklabels(labels); ax.set_ylabel("fraction of players retained")
ax.set_title("Cookie Cats: retention by version (95% normal intervals)")
ax.set_ylim(0, 0.56); ax.legend(frameon=False, loc="upper center", ncol=2); fig.tight_layout()
fig.savefig(os.path.join(FIG, "retention_by_version.png"), dpi=150); plt.close(fig)

fig, ax = plt.subplots(figsize=(5.5, 3.6))
for v, lab in zip(["gate_30", "gate_40"], labels):
    g = df.loc[df.version == v, "sum_gamerounds"].clip(upper=500)
    ax.hist(g, bins=60, alpha=0.5, label=lab, log=True)
ax.set_xlabel("game rounds in first 14 days (clipped at 500)"); ax.set_ylabel("players (log)")
ax.set_title("Engagement is heavily right-skewed"); ax.legend(frameon=False); fig.tight_layout()
fig.savefig(os.path.join(FIG, "gamerounds_hist.png"), dpi=150); plt.close(fig)

# ------------------------------------------------------------ LaTeX
n_rows, n_cols = df.shape
miss = int(df.isna().sum().sum())
L = ["% Generated by src/load_data.py -- do not edit by hand",
     f"\\newcommand{{\\dataRows}}{{{n_rows:,}}}".replace(",", "{,}"),
     f"\\newcommand{{\\dataCols}}{{{n_cols}}}",
     f"\\newcommand{{\\dataMissing}}{{{miss}}}",
     "\\begin{table}[ht]\\centering\\caption{Cookie Cats: trials $n$ and successes $x$ per version.}\\label{tab:data}",
     "\\begin{tabular}{lrrrrr}\\toprule version & $n$ & $x$ (1-day) & $x/n$ & $x$ (7-day) & $x/n$ \\\\ \\midrule"]
for v, lab in zip(["gate_30", "gate_40"], ["gate\\_30 (A)", "gate\\_40 (B)"]):
    r = summary.loc[v]
    L.append(f"{lab} & {int(r.n):,} & {int(r.x1):,} & {r.rate1:.4f} & {int(r.x7):,} & {r.rate7:.4f} \\\\".replace(",", "{,}"))
L += ["\\bottomrule\\end{tabular}\\end{table}"]
with open(os.path.join(DOCS, "data_macros.tex"), "w") as f:
    f.write("\n".join(L[:4]) + "\n")
with open(os.path.join(DOCS, "data_summary.tex"), "w") as f:
    f.write("\n".join([L[0]] + L[4:]) + "\n")
print("\nwrote docs/data_summary.tex and figures/*.png")
