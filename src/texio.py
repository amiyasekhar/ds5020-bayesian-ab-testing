"""
Small helpers that write script results into docs/ as LaTeX, so that every number
in the report is produced by a script (not typed by hand).  Not part of the method.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
DOCS = os.path.join(HERE, "..", "docs")
FIG = os.path.join(HERE, "..", "figures")
DATA = os.path.join(HERE, "..", "data", "cookie_cats.csv")
os.makedirs(DOCS, exist_ok=True)
os.makedirs(FIG, exist_ok=True)


def sci(x, digits=1):
    """1.234e-11 -> '1.2\\times10^{-11}' (math mode); exact zero -> '0'."""
    if x == 0:
        return "0"
    mant, exp = f"{x:.{digits}e}".split("e")
    return f"{mant}\\times10^{{{int(exp)}}}"


def thousands(k):
    """90189 -> '90{,}189'."""
    return f"{k:,}".replace(",", "{,}")


def row(data, quantity, compared, difference, passed):
    """One row of the verification table."""
    mark = "\\checkmark" if passed else "$\\times$"
    return f"{data} & {quantity} & {compared} & {difference} & {mark} \\\\"


def write_tex(name, macros=None, lines=None, script=""):
    """Write docs/<name>: \\newcommand macros (dict name -> text) and/or raw lines."""
    out = [f"% Generated by {script} -- do not edit by hand"]
    for key, val in (macros or {}).items():
        out.append(f"\\newcommand{{\\{key}}}{{{val}}}")
    out += list(lines or [])
    with open(os.path.join(DOCS, name), "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote docs/{name}")
